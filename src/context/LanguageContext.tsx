interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  isRtl: boolean;
  t: (typeof UI_DICTIONARY)[Locale];
}

const LanguageContext = createContext<LanguageContextValue>({
  locale: "tr",
  setLocale: () => {},
  isRtl: false,
  t: UI_DICTIONARY.tr,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("tr");

  useEffect(() => {
    try {
      // Clear any legacy localStorage value so the site always defaults to Turkish ("tr") on entry
      window.localStorage.removeItem("genc_group_locale");
    } catch {
      // ignore storage errors
    }
  }, []);

  const setLocale = (next: Locale) => {
    setLocaleState(next);
  };

  const isRtl = locale === "ar";

  return (
    <LanguageContext.Provider
      value={{
        locale,
        setLocale,
        isRtl,
        t: UI_DICTIONARY[locale],
      }}
    >
      <div
        dir={isRtl ? "rtl" : "ltr"}
        lang={locale}
        className="flex min-h-screen flex-col flex-1"
      >
        {children}
      </div>
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
